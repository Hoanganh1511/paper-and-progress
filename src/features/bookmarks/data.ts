const MINUTE = 60_000;
const DAY = 24 * 60 * MINUTE;

/**
 * The moment the sample data was written. It is a fixed value, not
 * `Date.now()`, because a page that is prerendered cannot read the clock. A
 * real fetch should return the time of the request instead.
 */
const SAMPLE_NOW = Date.parse("2026-10-27T12:00:00.000Z");

/**
 * The user's saved lessons and folders. It is static for now; replace the body
 * with a fetch and the page keeps working because it already awaits this.
 */
export async function getBookmarkLibrary(): Promise<BookmarkLibrary> {
  const now = SAMPLE_NOW;
  const bookmarks: Bookmark[] = SEEDS.map(
    ([
      id,
      title,
      folderId,
      domain,
      tags,
      contentType,
      level,
      status,
      progress,
      durationMinutes,
      daysAgo,
    ]) => ({
      id,
      title,
      description: `${title}: bài học bạn đã lưu để xem lại sau.`,
      href: "/learn",
      folderId,
      domain,
      tags,
      contentType,
      level,
      status,
      progress,
      durationMinutes,
      // Spread saves across the day so "today" items still order sensibly.
      savedAt: new Date(
        now - daysAgo * DAY - Number(id.slice(1)) * MINUTE,
      ).toISOString(),
    }),
  );

  return { bookmarks, folders: FOLDERS, now: new Date(now).toISOString() };
}
