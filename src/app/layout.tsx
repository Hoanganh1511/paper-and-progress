import type { Metadata } from "next";
import dynamic from "next/dynamic";
import { Geist, Geist_Mono } from "next/font/google";
import { SkipLink, ThemeScript } from "@/design-system";
import { AuthProvider, SessionHeader } from "@/features/auth";
import { AppFooter } from "@/features/footer";
import { HideOnRoutes } from "./HideOnRoutes";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

// Developer progress tracker. NODE_ENV is inlined at build time, so in a
// production build the ternary collapses and the import() below, and with it
// the whole widget, is left out of the bundle (a plain `import` would keep it).
const DevTodoWidget =
  process.env.NODE_ENV === "development"
    ? dynamic(() =>
        import("@/features/dev-todos").then((module) => module.DevTodoWidget),
      )
    : null;

// Placeholder values until the header is fed by the signed-in user's data
// (score, unread count); the user itself comes from the signed-in session and the footer links point at the real pages.
const FACEBOOK_COMMUNITY_URL = "https://www.facebook.com/";
const ZALO_SUPPORT_URL = "https://zalo.me/";
const SAMPLE_SCORE = 227;
const SAMPLE_PROFILE_BADGE = 1;

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      // ThemeScript sets the saved theme on <html> before React hydrates.
      suppressHydrationWarning
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <head>
        <ThemeScript />
      </head>
      <body className="min-h-full flex flex-col">
        {/* First in the page, so keyboard users can jump past the header. */}
        <SkipLink lang="vi">Bỏ qua đến nội dung chính</SkipLink>
        <AuthProvider>
          <SessionHeader
            isSticky
            facebookHref={FACEBOOK_COMMUNITY_URL}
            score={SAMPLE_SCORE}
            profileBadge={SAMPLE_PROFILE_BADGE}
          />
          {/* Grows to fill short pages, so the footer stays at the bottom. A
              column, so a page can in turn grow to fill it (e.g. to centre). */}
          <div className="flex flex-1 flex-col">{children}</div>
          {/* These pages fill exactly one screen, so no footer below them. */}
          <HideOnRoutes paths={["/devlog"]}>
            <AppFooter
              zaloHref={ZALO_SUPPORT_URL}
              communityHref={FACEBOOK_COMMUNITY_URL}
            />
          </HideOnRoutes>
        </AuthProvider>
        {DevTodoWidget && <DevTodoWidget />}
      </body>
    </html>
  );
}
