import type { Metadata } from "next";
import dynamic from "next/dynamic";
import { Geist, Geist_Mono } from "next/font/google";
import Script from "next/script";
import { Suspense } from "react";
import { SkipLink, ThemeScript, ToastProvider } from "@/design-system";
import { AuthProvider, SessionHeader } from "@/features/auth";
import { AppFooter } from "@/features/footer";
import { DailyGateLauncher } from "@/features/daily-gate";
import { RouterLinks } from "./RouterLinks";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

// Developer progress tracker. NODE_ENV is inlined at build time, so in a
// production build the ternary collapses and the import() below, and with it
// the whole widget, is left out of the bundle (a plain `import` would keep it).
const DevTodoWidget =
  process.env.NODE_ENV === "development"
    ? dynamic(() =>
        import("@/features/dev-todos").then((module) => module.DevTodoWidget),
      )
    : null;

// Placeholder values until the header is fed by the signed-in user's data
// (score, unread count); the user itself comes from the signed-in session and the footer links point at the real pages.
const RECAPTCHA_SITE_KEY = process.env.NEXT_PUBLIC_RECAPTCHA_SITE_KEY;
const FACEBOOK_COMMUNITY_URL = "https://www.facebook.com/";
const ZALO_SUPPORT_URL = "https://zalo.me/";
const SAMPLE_SCORE = 227;

export const metadata: Metadata = {
  // Absolute base for canonical links, Open Graph images and the sitemap.
  metadataBase: new URL(
    process.env.NEXT_PUBLIC_SITE_URL ?? "http://localhost:3000",
  ),
  title: "Create Next App",
  description: "Generated by create next app",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      // ThemeScript sets the saved theme on <html> before React hydrates.
      suppressHydrationWarning
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <head>
        <ThemeScript />
      </head>
      <body className="min-h-full flex flex-col">
        {/* reCAPTCHA v3 is invisible; without a site key (dev) it is not loaded. */}
        {RECAPTCHA_SITE_KEY && (
          <Script
            src={`https://www.google.com/recaptcha/api.js?render=${RECAPTCHA_SITE_KEY}`}
            strategy="afterInteractive"
          />
        )}
        {/* First in the page, so keyboard users can jump past the header. */}
        <SkipLink lang="vi">Bỏ qua đến nội dung chính</SkipLink>
        {/* Lets any screen show a short message ("Đã lưu") that leaves by itself. */}
        <ToastProvider lang="vi">
          <AuthProvider>
            {/* Internal links change page in the browser instead of loading it again. */}
            <RouterLinks>
              {/* These read the current path, which a dynamic route (/articles/[slug]) only knows at request time, so they stream in. */}
              <Suspense
                fallback={
                  <div
                    aria-hidden="true"
                    className="h-[var(--app-header-height,4rem)]"
                  />
                }
              >
                <SessionHeader
                  isSticky
                  facebookHref={FACEBOOK_COMMUNITY_URL}
                  score={SAMPLE_SCORE}
                />
              </Suspense>
              {/* Grows to fill short pages, so the footer stays at the bottom. A
              column, so a page can in turn grow to fill it (e.g. to centre). */}
              <div className="flex flex-1 flex-col">{children}</div>
              <AppFooter
                zaloHref={ZALO_SUPPORT_URL}
                communityHref={FACEBOOK_COMMUNITY_URL}
              />
              {/* Opens the Daily English Gate; stacks above the dev todo button in development. */}
              <Suspense fallback={null}>
                <DailyGateLauncher hasDevTodo={DevTodoWidget !== null} />
              </Suspense>
            </RouterLinks>
          </AuthProvider>
        </ToastProvider>
        {DevTodoWidget && <DevTodoWidget />}
      </body>
    </html>
  );
}
